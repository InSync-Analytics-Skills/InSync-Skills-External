def diff(a, b, path=""):
    out = []
    if isinstance(a, dict) and isinstance(b, dict):
        for k in sorted(set(a) | set(b)):
            if k.startswith("_"):
                continue
            if k not in a:
                out.append(path + "/" + k + ": only in rebuilt")
            elif k not in b:
                out.append(path + "/" + k + ": missing from rebuilt")
            else:
                out += diff(a[k], b[k], path + "/" + k)
    elif isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            out.append("%s: length %d -> %d" % (path, len(a), len(b)))
        idk = next((k for k in ("code", "ltcode", "key", "item", "q", "label")
                    if a and isinstance(a[0], dict) and k in a[0]), None)
        if idk:
            bb = {x.get(idk): x for x in b if isinstance(x, dict)}
            for x in a:
                if not isinstance(x, dict):
                    continue
                y = bb.get(x.get(idk))
                if y is None:
                    out.append("%s[%s]: missing from rebuilt" % (path, x.get(idk)))
                else:
                    out += diff(x, y, "%s[%s]" % (path, x.get(idk)))
        else:
            for i, (x, y) in enumerate(zip(a, b)):
                out += diff(x, y, "%s[%d]" % (path, i))
    else:
        na, nb = num(a), num(b)
        if na is not None and nb is not None:
            if abs(na - nb) > 5e-4:
                out.append("%s: %r -> %r" % (path, a, b))
        elif a != b:
            out.append("%s: %r -> %r" % (path, a, b))
    return out


