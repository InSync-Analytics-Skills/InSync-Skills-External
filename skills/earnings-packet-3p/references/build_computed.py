def _blank(x):
    if isinstance(x, dict):
        return {k: _blank(v) for k, v in x.items()}
    if isinstance(x, list):
        if not x:
            return []
        if isinstance(x[0], (dict, list)):
            return [_blank(x[0])]
        return []
    if isinstance(x, bool):
        return x
    return None


