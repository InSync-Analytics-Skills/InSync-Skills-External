def _sdiff(a, b):
    if a == b and type(a) is type(b) and (not isinstance(a, dict) or list(a) == list(b)):
        return None
    if isinstance(a, dict) and isinstance(b, dict):
        d = {}
        for k in b:
            if k in a:
                x = _sdiff(a[k], b[k])
                if x is not None:
                    d[k] = x
            else:
                d[k] = {"__new__": b[k]}
        for k in a:
            if k not in b:
                d[k] = "__del__"
        if list(b) != [k for k in a if k in b] + [k for k in b if k not in a]:
            d["__order__"] = list(b)
        return d
    return {"__new__": b}


def _spatch(a, d):
    if d is None:
        return a
    if isinstance(d, dict) and "__new__" in d and len(d) == 1:
        return d["__new__"]
    out = {}
    for k in a:
        if d.get(k) == "__del__":
            continue
        out[k] = _spatch(a[k], d[k]) if k in d else a[k]
    for k, v in d.items():
        if k == "__order__" or k in a:
            continue
        out[k] = v["__new__"]
    if "__order__" in d:
        out = {k: out[k] for k in d["__order__"]}
    return out


