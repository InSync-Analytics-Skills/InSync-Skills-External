#!/usr/bin/env python3
"""earnings-packet-3p, the raw-to-computed builder. Closes the last hand-typing step.

    python3 references/build_computed.py --scaffold <sector_key> --ticker <T>
    python3 references/build_computed.py --explode packet_computed.json
    python3 references/build_computed.py --build            # reads plan.json + raw_mcp.json
    python3 references/build_computed.py --verify packet_computed.json

THE SCAFFOLD, AND WHY IT IS PART OF THE BUILDER
-----------------------------------------------
`--scaffold` writes a `plan.json` and a `raw_mcp.json` carrying EVERY key the builder will
read, with the sector's own spine, bands, lens order and tile set already in place and every
VALUE blanked to null. It exists so the shape of the two input files is something the
operator is handed rather than something they infer from a contract document: reading
`pipeline-contracts.md` and `packet-schema.json` to learn a shape costs about fourteen
thousand tokens of context on every run, and the shape is already known to this file.

It is `--explode` run against the bundled fixture for the sector, with the values removed.
That is deliberate: the scaffold is generated by the same code path the round-trip test
exercises, so a scaffold that has drifted from what `build()` reads is a `--explode` bug and
the round-trip test (internal edition only) catches it. An array of objects keeps ONE blanked exemplar rather than
the fixture's row count, because the shape is the deliverable and the count is the issuer's.

A leftover null is a HARD ERROR naming the field, which is the existing contract: the
scaffold cannot silently ship a fixture's value into a real packet, because it carries none.

WHY THIS FILE EXISTS
--------------------
Every other control in this skill exists to stop a number being invented, and one step in
the middle would undo them all if done by hand: transcribing figures out of the MCP response
into `packet_computed.json`, roughly two hundred lines of it per company. That is the only
place a figure can be mis-keyed. `compute.py --audit` catches a figure that contradicts another figure, which is
most mistakes; it cannot catch one copied wrong CONSISTENTLY, because that is internally
coherent and passes everything.

THE SPLIT, WHICH IS THE WHOLE DESIGN
------------------------------------
The mapping looked irreducibly issuer-specific, and about a fifth of it is. The rest is
arithmetic, and the proof was already in the bundle: `compute.py --audit` re-derives growth,
dispersion, the reaction identities, the valuation comparisons and the peer ratios. Anything
it can RE-derive, it can derive. So:

    plan.json      DECISIONS ONLY, and no numbers. Which LTCODE fills which role, the
                   display name, the format, the sub-row kind, the band labels, the lens
                   order, the twelve tile labels and where each tile reads its figure from.
                   About forty lines.

    raw_mcp.json   the feed's own values, dumped rather than transcribed.

    -> build_computed.py -> packet_computed.json, with every growth rate, margin,
       dispersion spread, revision delta, reaction move, move-band statistic and valuation
       comparison DERIVED rather than typed.

WHAT IS STILL AUTHORED, AND HONESTLY
------------------------------------
Two things, both small and both deliberate. `meta` carries dates and labels that come from
`search_tickerid` and `get_call_date` and are not arithmetic. And a tile may carry a
verbatim `value` where it shows something outside the derivable set. Every tile in the
bundled fixtures uses a `from` spec instead, so the derivation is exercised rather than
merely offered.

THE ACCEPTANCE TEST
-------------------
`--verify` explodes an existing computed file into a plan-and-raw pair, rebuilds it, and
reports any field that came back different. The fixture matrix (internal edition only) does
that for every fixture and additionally requires the REBUILT file to render a byte-identical
`word/document.xml`. Equivalent JSON is not the bar; the page is, because key order and
absent-versus-null are exactly where a rebuild drifts.

ADOPTION, DELIBERATELY CAUTIOUS
-------------------------------
`--build` writes `packet_computed.candidate.json`, not over the real file, unless `--force`
is passed. Diff the candidate against a hand-authored file on a name the builder was not
developed against, twice, before making it the path anything depends on.

REFUSES RATHER THAN GUESSES
---------------------------
A field it cannot derive is a hard error naming the field. It never emits a null and lets
the prune quietly absorb it: that would turn a fetch gap into a layout decision with no
disclosure, which is what rule 7 exists to prevent.
"""
